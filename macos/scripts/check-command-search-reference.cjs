if (start < 0 || end <= start) throw new Error('Cannot locate the renderer fuzzyScore function');
const source = renderer.slice(start, end);
const fuzzyScore = vm.runInNewContext(`${source}\nfuzzyScore`, Object.create(null), { timeout: 1000 });

